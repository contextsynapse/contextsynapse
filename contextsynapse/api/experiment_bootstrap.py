def _gen_swarm(name, role, prompt, key, session, graph, url):
    return f'''"""
{name} — OpenAI Swarm agent connected to AIContextDB.
"""
from contextsynapse import AIContextDB
from contextsynapse.adapters.swarm import create_swarm_tools
from swarm import Swarm, Agent

db = AIContextDB.connect(api_url="{url}", api_key="{key}", graph="{graph}")
tools = create_swarm_tools(db)

agent = Agent(
    name="{name}",
    instructions="You are {name}, a {role}. {prompt}",
    functions=tools,
)

client = Swarm()
response = client.run(agent=agent, messages=[{{"role": "user", "content": "{prompt}"}}])
print(response.messages[-1]["content"])
'''


def _gen_mcp_raw(name, role, prompt, key, session, graph, url):
    return f'''"""
{name} — Raw MCP client connected to AIContextDB.
No framework needed — uses AIContextDB SDK directly.
"""
from contextsynapse import AIContextDB, ContextHub

# Connect
db = AIContextDB.connect(
    api_url="{url}",
    api_key="{key}",
    graph="{graph}",
    session_id="{session}" or None,
)

# Search the graph
results = db.search("{prompt[:50]}")
print(f"Found {{len(results)}} results")

# Build context for LLM
hub = ContextHub(db)
context = hub.build(system_prompt="You are {name}, a {role}.")
messages = context.to_messages()
messages.append({{"role": "user", "content": "{prompt}"}})

# Call any LLM with the context
print("Context ready with", len(messages), "messages")
print("System prompt:", messages[0]["content"][:200])
'''
